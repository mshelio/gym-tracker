const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
const schemaText=fs.readFileSync(path.join(root,'ppl-tracker-data.schema.json'),'utf8');
const found=source.match(/^const DATA_SCHEMA = (.+);$/m);
assert(found,'inline import validator schema must be present');
assert.deepEqual(JSON.parse(found[1]),JSON.parse(schemaText),'runtime and downloadable v4 schema must remain in sync');
const template=JSON.parse(fs.readFileSync(path.join(root,'ppl-tracker-data.json'),'utf8'));
assert.equal(template.version,4,'template must remain v4');
assert.equal(template.app,'ppl-tracker');
const schema=JSON.parse(schemaText);
assert.equal(schema.properties.version.const,4);
for(const key of schema.required)assert(Object.hasOwn(template,key),'backup template missing '+key);
const readme=fs.readFileSync(path.join(root,'README.md'),'utf8');
assert.match(readme,/IndexedDB/);
assert.match(readme,/version 4 app-data template/);
assert.match(readme,/Calendar/);
const changelog=fs.readFileSync(path.join(root,'CHANGELOG.md'),'utf8');
assert.match(changelog,/v1\.3\.0 release candidate/);
assert.match(changelog,/v1\.2\.0/);
assert.match(changelog,/v1\.3\.0 has not been tagged or published/);
assert.match(readme,/v1\.3\.0 remains unreleased/);
const draft=fs.readFileSync(path.join(root,'docs/releases/v1.3.0-draft.md'),'utf8');
assert.match(draft,/NOT tagged or published/);
assert.match(draft,/backup format v4/);
console.log('PASS: v4 schema parity, template, release docs and changelog');
