const assert=require("node:assert/strict");
const fs=require("node:fs"),path=require("node:path");
(async()=>{
 const root=path.join(__dirname,"..");
 const mapSource=fs.readFileSync(path.join(root,"js/muscle-map-data.js"),"utf8");
 const map=await import("data:text/javascript;base64,"+Buffer.from(mapSource).toString("base64"));
 const anatomySource=fs.readFileSync(path.join(root,"js/anatomy-paths.js"),"utf8");
 const {ANATOMY_PATHS}=await import("data:text/javascript;base64,"+Buffer.from(anatomySource).toString("base64"));
 assert.equal(ANATOMY_PATHS.front.length,40);
 assert.equal(ANATOMY_PATHS.back.length,49);
 const viewSource=fs.readFileSync(path.join(root,"js/muscle-map-view.js"),"utf8").replace(/^import .*;\s*/gm,"").replace(/export /g,"");
 const view=new Function("MUSCLE_REGIONS","ANATOMY_PATHS",viewSource+"\nreturn {renderMuscleMap,bindMuscleMap,renderExerciseMusclePreview};")(map.MUSCLE_REGIONS,ANATOMY_PATHS);
 const data=map.muscleMapData({unit:"kg",secondaryCredit:0.5,primary:[{muscle:"chest",hardSets:4,volume:1200}],secondary:[{muscle:"triceps",hardSets:2,volume:600}],unknown:{hardSets:1,volume:100}});
 const html=view.renderMuscleMap(data,{selected:"chest"});
 assert.match(html,/Front view/);assert.match(html,/Back view/);
 assert.match(html,/id="front-chest-left"/);assert.match(html,/role="button" tabindex="0"/);
 assert.match(html,/aria-pressed="true"/);assert.match(html,/Secondary credited sets/);
 assert.match(html,/Unknown exercises: 1 hard sets/);
 assert.match(html,/id="front-neck-left"[^>]+class="muscle-map__anatomy-base" aria-hidden="true"/);
 const withContributors=view.renderMuscleMap(data,{selected:"chest",contributors:[{muscle:"chest",name:"Bench <Press>",kind:"primary",hardSets:4,volume:1200},{muscle:"triceps",name:"Press",kind:"secondary",hardSets:2,volume:600}]});
 assert.match(withContributors,/Contributing exercises \(1\)/);
 assert.match(withContributors,/Bench &lt;Press&gt;/);
 assert.doesNotMatch(withContributors,/Secondary \(0\.5\)/);
 assert.match(withContributors,/Small regions can be selected by name/);
 const secondaryContributors=view.renderMuscleMap(data,{selected:"triceps",contributors:[{muscle:"triceps",name:"Press",kind:"secondary",hardSets:2,volume:600}]});
 assert.match(secondaryContributors,/Secondary \(0\.5\)/);
 const empty=view.renderMuscleMap(map.muscleMapData({unit:"lb",primary:[],secondary:[]}));
 assert.match(empty,/Highest relative activity \(0\)/);
 assert.throws(()=>view.renderMuscleMap(null));
 const preview=view.renderExerciseMusclePreview({primaryMuscle:"chest",secondaryMuscles:["triceps","shoulders"]});
 assert.match(preview,/Primary:<\/strong> Chest/);
 assert.match(preview,/Secondary:<\/strong> Triceps, Shoulders/);
 assert.match(preview,/muscle-map__activation--primary/);
 assert.match(preview,/muscle-map__activation--secondary/);
 assert.match(view.renderExerciseMusclePreview(null),/unavailable/);
 const listeners={};
 const container={addEventListener:(t,f)=>listeners[t]=f,removeEventListener:(t)=>delete listeners[t],contains:()=>true};
 const selected=[];
 const unsub=view.bindMuscleMap(container,m=>selected.push(m));
 const target={dataset:{muscle:"chest"},closest(){return this;}};
 listeners.click({type:"click",target});
 listeners.keydown({type:"keydown",target,key:"Enter",preventDefault(){}});
 listeners.keydown({type:"keydown",target,key:"Escape",preventDefault(){throw Error("unexpected")}});
 assert.deepEqual(selected,["chest","chest"]);
 unsub();assert.equal(Object.keys(listeners).length,0);
 console.log("Muscle-map SVG renderer tests passed");
})().catch(error=>{console.error(error);process.exitCode=1});
